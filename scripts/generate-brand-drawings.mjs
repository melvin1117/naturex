#!/usr/bin/env node
// Regenerates the brand's drawings from their sources of truth, so nothing is redrawn by hand:
//   - the WildWorth icon pack, from the `GL` object in docs/design/wildworth-brand-guidelines.html;
//   - Bea's six states, from `bea()` and `face()` in docs/design/bea-character.html.
// Run: node scripts/generate-brand-drawings.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const camel = (name) => {
  if (name === "class") return "className";
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
};

/** Attributes as a browser's HTML parser keeps them: the first of a repeated name wins. */
function attrs(raw) {
  const out = {};
  for (const [, name, value] of raw.matchAll(/([a-zA-Z-:]+)="([^"]*)"/g)) {
    const key = camel(name);
    if (!(key in out)) out[key] = value;
  }
  return out;
}

/** Markup → [tag, attrs, children] trees. */
function parse(markup) {
  const root = { children: [] };
  const stack = [root];
  for (const [, close, tag, raw, self] of markup.matchAll(/<(\/?)(\w+)([^>]*?)(\/?)>/g)) {
    if (close) {
      stack.pop();
      continue;
    }
    const node = [tag, attrs(raw), []];
    stack[stack.length - 1].children.push(node);
    if (!self) stack.push({ node, children: node[2] });
  }
  return root.children;
}

// ---- the icon pack ------------------------------------------------------------------------------

const guidelines = read("docs/design/wildworth-brand-guidelines.html");
const glStart = guidelines.indexOf("var GL={");
const glEnd = guidelines.indexOf("};", glStart);
if (glStart < 0 || glEnd < 0) throw new Error("GL object not found in the guidelines");
const GL = vm.runInNewContext(`(${guidelines.slice(glStart + "var GL=".length, glEnd + 1)})`);

/** Flat nodes for `createLucideIcon`; a `<g transform>` is folded into its children. */
function flat(trees, transform) {
  return trees.flatMap(([tag, a, children]) => {
    if (tag === "g") return flat(children, [transform, a.transform].filter(Boolean).join(" "));
    return [[tag, transform ? { ...a, transform: [transform, a.transform].filter(Boolean).join(" ") } : a]];
  });
}

const icons = {};
for (const [key, markup] of Object.entries(GL)) {
  if (key === "bea") continue; // Bea's icon is her drawing, scaled down (components/bea).
  icons[key] = flat(parse(markup)).map(([tag, a], i) => [tag, { ...a, key: `${key}-${i}` }]);
}
writeFileSync(
  join(root, "frontend/src/components/icons/drawings.ts"),
  `// Generated by scripts/generate-brand-drawings.mjs from the \`GL\` object in
// docs/design/wildworth-brand-guidelines.html. Don't edit: change the guidelines and regenerate.
import type { IconNode } from "lucide-react";

export const DRAWINGS = {
${Object.entries(icons)
  .map(([key, n]) => `  ${JSON.stringify(key)}: ${JSON.stringify(n)},`)
  .join("\n")}
} as const satisfies Record<string, IconNode>;

export type DrawingKey = keyof typeof DRAWINGS;
`,
);

// ---- Bea ----------------------------------------------------------------------------------------

const sheet = read("docs/design/bea-character.html");
const fn = (name) => {
  const at = sheet.indexOf(`function ${name}(`);
  const next = sheet.indexOf("\n  function ", at + 1);
  const stop = sheet.indexOf("\n  /*", at + 1);
  return sheet.slice(at, Math.min(...[next, stop].filter((i) => i > at)));
};
const header = sheet.slice(sheet.indexOf("var SW="), sheet.indexOf("\n\n  function face("));
const context = { result: {} };
vm.runInNewContext(
  `${header}\n${fn("face")}\n${fn("bea")}\n` +
    `for (const e of ["neutral","think","happy","alert","sad","sleep"]) result[e] = bea(e);`,
  context,
);

/** The ground fill (`--chbg` on the sheet) becomes a class; the clip path's id a placeholder. */
function bea(trees) {
  return trees.map(([tag, a, children]) => {
    const out = { ...a };
    if (out.style === "fill:var(--chbg)") {
      delete out.style;
      out.className = [out.className, "bea-ground"].filter(Boolean).join(" ");
    }
    if (out.id?.startsWith("bc")) out.id = "CLIP";
    if (out.clipPath?.startsWith("url(#bc")) out.clipPath = "url(#CLIP)";
    return [tag, out, bea(children)];
  });
}
const states = Object.fromEntries(
  Object.entries(context.result).map(([state, markup]) => [state, bea(parse(markup))]),
);
writeFileSync(
  join(root, "frontend/src/components/bea/drawings.ts"),
  `// Generated by scripts/generate-brand-drawings.mjs from \`bea()\` and \`face()\` in
// docs/design/bea-character.html. Don't edit: change the character sheet and regenerate.

export type BeaNode = readonly [string, Readonly<Record<string, string>>, readonly BeaNode[]];

export const BEA = {
${Object.entries(states)
  .map(([state, n]) => `  ${state}: ${JSON.stringify(n)},`)
  .join("\n")}
} as const satisfies Record<string, readonly BeaNode[]>;

export type BeaDrawingState = keyof typeof BEA;
`,
);
console.log(`Wrote ${Object.keys(icons).length} icons and ${Object.keys(states).length} Bea states`);
